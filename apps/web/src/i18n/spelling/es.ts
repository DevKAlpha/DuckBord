/** Nouns with a tilde that are also verbs without it: «el número», «yo numero», «ya numeró». */
for (const [plain, noun, gloss] of [
  ['publico', 'público', 'gente o abierto'],
  ['practico', 'práctico', 'útil'],
  ['practica', 'práctica', 'ejercicio'],
  ['ultimo', 'último', 'final'],
  ['termino', 'término', 'palabra o plazo'],
  ['calculo', 'cálculo', 'cuenta'],
  ['critico', 'crítico', 'grave'],
  ['deposito', 'depósito', 'lugar o pago'],
  ['valido', 'válido', 'correcto'],
  ['numero', 'número', 'cifra'],
  ['articulo', 'artículo', 'texto o producto'],
  ['titulo', 'título', 'nombre'],
  ['vinculo', 'vínculo', 'enlace'],
  ['diagnostico', 'diagnóstico', 'resultado'],
  ['especifico', 'específico', 'concreto'],
  ['medico', 'médico', 'doctor'],
  ['animo', 'ánimo', 'energía'],
  ['habito', 'hábito', 'costumbre'],
  ['circulo', 'círculo', 'figura'],
  ['limite', 'límite', 'borde'],
] as const) {
  const stem = plain.slice(0, -1);
  // -o: «yo publico» / «ya publicó». -e: «que limite» / «yo limité». -a: «hoy practica».
  const readings: [string, string][] = [[noun, gloss]];
  if (plain.endsWith('o')) readings.push([plain, `yo ${plain}`], [`${stem}ó`, `ya ${stem}ó`]);
  else if (plain.endsWith('e')) readings.push([plain, `que ${plain}`], [`${stem}é`, `yo ${stem}é`]);
  else readings.push([plain, `hoy ${plain}`]);
  ambiguous[plain] ??= { readings };
}

